FIO = re.compile(r"\b[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)? [А-ЯЁ][а-яё]+(?: [А-ЯЁ][а-яё]+(?:вич|вна|ич|на))?\b")
PHONE = re.compile(r"(?:тел\.?\s*)?\+?\d[\d\s-]{8,}\d")
ROLE = re.compile(r"\((?:очевидец|прохожий|посетитель|сосед|соседка|подруга|работник[^)]*|старшая[^)]*)\)")
CALLER = re.compile(r"(?:,\s*)?(?:Вызывает|вызывает)[^,.]*[,.]?")


def speech(situation: str) -> str:
    """Первая реплика заявителя: ситуация без его имени, телефона и служебных пометок."""
    text = PHONE.sub("", situation)
    text = ROLE.sub("", text)
    text = CALLER.sub(",", text)
    text = re.sub(r"д/р\s*[\d.]+г?\.?", "", text)
    for name in FIO.findall(text):
        text = text.replace(name, "")
    text = re.sub(r"\s*,\s*(,\s*)+", ", ", text)
    text = re.sub(r"\s+", " ", text).strip(" ,.;")
    return "Алло, 112? " + text[0].upper() + text[1:] + "."


def gender(name: str) -> str:
    first = name.split()[0]
    return "f" if first.endswith(("а", "я")) and not first.endswith(("ия", "ья")) or first.endswith("ва") else "m"


def build() -> dict:
    src = json.loads(SRC.read_text(encoding="utf-8"))
    by_id = {c["id"]: c for c in src["calls"]}
    missing = [k for k in by_id if k not in A and k not in DUPLICATES]
    if missing:
        raise SystemExit("нет разметки для: %s" % ", ".join(missing))
    calls = []
    for key, (codes, flags, victims, statuses, subject, address, facts, name, name_checked) in A.items():
        c = by_id[key]
        caller_name = name.replace(" (вымышлено)", "")
        victims_text = {True: "Да, есть пострадавшие.", False: "Пострадавших нет.", None: "Не знаю, не вижу."}[victims]
        danger = "Да, людям угрожает опасность!" if "УЛ" in flags else "Угрозы людям вроде нет."
        text = c["situation"].lower()
        gas = ("Дом газифицирован." if "ГАЗ" in flags else
               "Нет, дом не газифицирован." if "не газифицир" in text else "Не знаю.")
        calls.append({
            "key": key,
            "ticket": c["ticket"],
            "situation": c["situation"],
            "caller": {"name": caller_name, "phone": c["caller_phone"], "gender": gender(caller_name)},
            "gold": {
                "codes": codes,
                "flags": flags,
                "victims": victims,
                "statuses": statuses,
                "name": caller_name if name_checked else None,
                "address": dict(address or {}, subject=subject),
                "facts": facts,
            },
            "dialogue": {
                "opening": speech(c["situation"]),
                "address": c["address_declared"],
                "address_clarified": c["address_clarified"] or c["address_declared"],
                "name": "Меня зовут %s." % caller_name,
                "phone": "Мой номер — %s." % c["caller_phone"],
                "victims": victims_text,
                "status": STATUS_SPEECH[statuses[0]],
                "details": c["situation"],
                "danger": danger,
                "gas": gas,
                "access": "Доступа нет." if "НД" in flags else "Доступ есть.",
            },
        })
    return {
        "id": "calls-bilety-v1",
        "title": "Вызовы из билетов: заполнение карточки 112",
        "mode": "cards",
        "source": "Билеты-задачи Службы 112 (транскрипция в data/scenarios/bilety.json); эталон карточки размечен "
                  "по классификатору v.046.24 в tools/build_calls_pack.py",
        "norm_s": 80,
        "answer_norm_s": 15,
        "duplicates": DUPLICATES,
        "calls": calls,
    }


def main() -> int:
    pack = build()
    OUT.write_text(json.dumps(pack, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("%s: %d вызовов" % (OUT.name, len(pack["calls"])))
    return 0


